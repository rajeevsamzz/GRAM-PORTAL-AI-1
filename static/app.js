const originalTextMap = new WeakMap();

function normalizeText(value) {
    return (value || "").replace(/\s+/g, " ").trim();
}

function rememberOriginalText(node) {
    const text = normalizeText(node.textContent || "");
    if (!text || node.parentElement && node.parentElement.classList && node.parentElement.classList.contains("language-toggle")) return;
    if (!originalTextMap.has(node)) {
        originalTextMap.set(node, text);
    }
}

function getOriginalText(node) {
    rememberOriginalText(node);
    return originalTextMap.get(node) || normalizeText(node.textContent || "");
}

function updateLanguageButtons(language) {
    document.querySelectorAll(".language-toggle").forEach((button) => {
        const isKannada = language === "kn";
        button.classList.toggle("active", isKannada);
        button.setAttribute("aria-pressed", String(isKannada));
        button.textContent = isKannada ? "English" : "ಕನ್ನಡ";
        button.dataset.lang = language;
    });
}

function translateTextNode(node, language) {
    if (!node || node.nodeType !== Node.TEXT_NODE) return;
    const original = getOriginalText(node);
    if (!original) return;

    if (language === "kn") {
        const translated = translations.kn[original] || original;
        node.textContent = translated;
    } else {
        node.textContent = original;
    }
}

function translatePlaceholder(element, language) {
    if (!element || !(element instanceof HTMLElement)) return;
    if (!(element.tagName === "INPUT" || element.tagName === "TEXTAREA")) return;
    const current = element.getAttribute("placeholder") || "";
    if (!current) return;
    if (!element.__originalPlaceholder) element.__originalPlaceholder = current;
    const original = element.__originalPlaceholder;

    if (language === "kn") {
        const translated = translations.kn[original] || original;
        element.setAttribute("placeholder", translated);
    } else {
        element.setAttribute("placeholder", original);
    }
}

function applyLanguage(language) {
    document.documentElement.lang = language;
    updateLanguageButtons(language);

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) {
        const node = walker.currentNode;
        const parent = node.parentElement;
        if (!parent || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(parent.tagName)) continue;
        if (parent.classList && parent.classList.contains("language-toggle")) continue;
        translateTextNode(node, language);
    }

    document.querySelectorAll("input[placeholder], textarea[placeholder]").forEach((element) => {
        translatePlaceholder(element, language);
    });

    const voiceStatus = document.getElementById("voice-status");
    if (voiceStatus) {
        const englishStatus = "English voice input is available in supported browsers.";
        const kannadaStatus = "ಬೆಂಬಲಿತ ಬ್ರೌಸರ್‌ಗಳಲ್ಲಿ ಇಂಗ್ಲಿಷ್ ಧ್ವನಿ ಇನ್‌ಪುಟ್ ಲಭ್ಯವಿದೆ.";
        voiceStatus.textContent = language === "kn" ? kannadaStatus : englishStatus;
    }
}

function toggleLanguage(targetLanguage) {
    const nextLanguage = targetLanguage || (document.documentElement.lang === "kn" ? "en" : "kn");
    applyLanguage(nextLanguage);
}

document.addEventListener("DOMContentLoaded", () => {
    const startLanguage = document.documentElement.lang || "en";
    applyLanguage(startLanguage);

    const interactiveCards = document.querySelectorAll(".card, .stat");

    interactiveCards.forEach((card) => {
        card.addEventListener("pointermove", (event) => {
            if (window.matchMedia("(pointer: coarse)").matches) return;
            const bounds = card.getBoundingClientRect();
            const x = ((event.clientX - bounds.left) / bounds.width - 0.5) * 2;
            const y = ((event.clientY - bounds.top) / bounds.height - 0.5) * 2;
            card.style.transform = `perspective(700px) rotateY(${x * 2}deg) rotateX(${y * -2}deg) translateY(-8px)`;
        });

        card.addEventListener("pointerleave", () => {
            card.style.transform = "";
        });
    });

    document.querySelectorAll(".btn, button, nav a").forEach((element) => {
        element.addEventListener("click", (event) => {
            if (element.classList && element.classList.contains("language-toggle")) return;
            const ripple = document.createElement("span");
            const bounds = element.getBoundingClientRect();
            ripple.className = "ripple";
            ripple.style.left = `${event.clientX - bounds.left}px`;
            ripple.style.top = `${event.clientY - bounds.top}px`;
            element.appendChild(ripple);
            ripple.addEventListener("animationend", () => ripple.remove());
        });
    });

    document.querySelectorAll("form").forEach((form) => {
        form.addEventListener("submit", () => {
            const submitButton = form.querySelector("button[type='submit'], button:not([type])");
            if (submitButton) {
                submitButton.classList.add("is-loading");
                submitButton.textContent = "Working...";
            }
        });
    });

    applyLanguage(document.documentElement.lang || "en");
});

function startVoiceInput() {
    const SpeechRecognition = window.SpeechRecognition || window.webkitSpeechRecognition;
    const status = document.getElementById("voice-status");
    if (!SpeechRecognition) {
        status.textContent = "Voice input is unavailable in this browser.";
        return;
    }
    const recognition = new SpeechRecognition();
    recognition.lang = document.documentElement.lang === "kn" ? "kn-IN" : "en-IN";
    recognition.interimResults = false;
    recognition.onresult = (event) => {
        document.getElementById("description").value = event.results[0][0].transcript;
        status.textContent = document.documentElement.lang === "kn" ? "ಧ್ವನಿ ಸೆರೆಹಿಡಿಯಲಾಗಿದೆ." : "Voice captured.";
    };
    recognition.onerror = () => {
        status.textContent = document.documentElement.lang === "kn" ? "ಧ್ವನಿ ಇನ್‌ಪುಟ್ ಪಡೆಯಲು ಸಾಧ್ಯವಾಗಲಿಲ್ಲ. ನೀವು ಟೈಪ್ ಮಾಡಬಹುದು." : "Voice input could not be captured. You can type instead.";
    };
    status.textContent = document.documentElement.lang === "kn" ? "ಕೇಳುತ್ತಿದೆ..." : "Listening...";
    recognition.start();
}

